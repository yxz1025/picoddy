import { readFile, writeFile, mkdir } from 'node:fs/promises';
import ts from 'typescript';

const targets = [
  ['runtime-source/document-editor.ts', 'runtime/document-editor.mjs'],
];
for (const [source, target] of targets) {
  let text = await readFile(source, 'utf8');
  const compiled = ts.transpileModule(text, { compilerOptions: { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.ESNext } });
  await mkdir(target.slice(0, target.lastIndexOf('/')), { recursive: true });
  await writeFile(target, '// Generated by scripts/generate-portable-runtime.ts; edit the cloud source, not this file.\n'+compiled.outputText);
}
